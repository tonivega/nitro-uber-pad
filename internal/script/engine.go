// Host is implemented by the UI and operates on the active document.
type Host interface {
	Text() string
	SetText(string)
	Insert(string)
	Path() string
	Title() string
	IsNew() bool
	Modified() bool
	Size() int64
	Save(force bool) error
	SaveAs(path string) error
	SaveAsDialog()
	Page() (int64, int64)
	GotoPage(int64)
	Prompt(title, label, def string, cb func(string, bool))
	Confirm(title, msg string, cb func(bool))
	Alert(msg string)
	Notify(msg string)
	OpenFile(path string) error
	OpenDialog()
	NewTab()
	CloseTab()
	GetVar(key string) (string, bool)
	SetVar(key, value string)
	Vars() map[string]string
	Cursor() (int, int)
	SetCursor(row, col int)
	DiskChanged() bool
	Reload() error
	HTTPTimeout() time.Duration
}

